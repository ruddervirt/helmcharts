// Package chartgen turns an upstream release into a Helm chart.
//
// It supports two project shapes (see upstream.Shape): an operator with a custom
// resource, and a set of CRDs picked from one file.
package chartgen

import (
	"bytes"
	"embed"
	"fmt"
	"io/fs"
	"regexp"
	"slices"
	"sort"
	"strings"
	"text/template"

	"sigs.k8s.io/yaml"

	"github.com/ruddervirt/kubevirt/internal/manifest"
	"github.com/ruddervirt/kubevirt/internal/upstream"
)

//go:embed all:templates
var staticFS embed.FS

// KeepAnnotation stops "helm uninstall" from deleting a resource.
const KeepAnnotation = "helm.sh/resource-policy"

// Placeholders survive yaml.Marshal as plain scalars and are then replaced with
// template expressions.
const (
	phNamespace = "HELMTPL__NAMESPACE__HELMTPL"
	phVersion   = "HELMTPL__VERSION__HELMTPL"
	phImage     = "HELMTPL__IMAGE__%s__HELMTPL"
)

var phImageRe = regexp.MustCompile(`HELMTPL__IMAGE__([a-z0-9-]+)__HELMTPL`)

// Input is one upstream release.
type Input struct {
	Project  *upstream.Project
	Tag      string
	Fix      int
	Operator []byte // ShapeOperator: <x>-operator.yaml
	CR       []byte // ShapeOperator: <x>-cr.yaml
	Source   []byte // ShapeCRDs: Project.SourceFile at Tag
}

// crdsData is passed to the static templates of ShapeCRDs.
type crdsData struct {
	*upstream.Project
	Tag     string
	Version string
}

// templateData is passed to the static templates (delimiters [[ ]]).
type templateData struct {
	*upstream.Project
	Tag             string
	Version         string
	CRAPIVersion    string
	CRSpecYAML      string
	NamespaceLabels []string
	Images          []string
	CRDFile         string
	// FollowImageTag is Project.FollowImageTag, except for the versions in
	// upstream.ChartsBeforeFollowImageTag.
	FollowImageTag bool
}

// Generate returns the chart files, keyed by path relative to the chart directory.
func Generate(in Input) (map[string][]byte, error) {
	version, err := upstream.ChartVersion(in.Tag, in.Fix)
	if err != nil {
		return nil, err
	}
	switch in.Project.Shape {
	case upstream.ShapeOperator:
		return generateOperator(in, version)
	case upstream.ShapeCRDs:
		return generateCRDs(in, version)
	default:
		return nil, fmt.Errorf("project %s: unknown shape %q", in.Project.Name, in.Project.Shape)
	}
}

// generateCRDs makes a chart that contains only the listed CRDs of Source.
// The CRDs go to templates/, not crds/, so that "helm upgrade" applies a new CRD.
func generateCRDs(in Input, version string) (map[string][]byte, error) {
	p := in.Project
	crds, err := SelectCRDs(p, in.Source)
	if err != nil {
		return nil, fmt.Errorf("%s %s: upstream layout changed: %w", p.SourceFile, in.Tag, err)
	}
	header := fmt.Sprintf("# Code generated by chartgen from %s %s %s. DO NOT EDIT.\n", p.Repo, in.Tag, p.SourceFile)
	files := map[string][]byte{}
	for _, crd := range crds {
		manifest.SetAnnotation(crd, KeepAnnotation, "keep")
		b, err := yaml.Marshal(crd)
		if err != nil {
			return nil, err
		}
		files["templates/"+manifest.Name(crd)+".yaml"] = append([]byte(header), escapeBraces(string(b))...)
	}
	if err := renderStatic(files, "crds", crdsData{Project: p, Tag: in.Tag, Version: version}, p.Name); err != nil {
		return nil, err
	}
	return files, nil
}

// SelectCRDs returns the CRDs of data that the project lists, in the order of
// Project.CRDNames. Documents of other kinds are dropped. It fails if a listed CRD
// is missing, or if data has a CRD that the project does not list.
func SelectCRDs(p *upstream.Project, data []byte) ([]manifest.Object, error) {
	objs, err := manifest.Split(data)
	if err != nil {
		return nil, err
	}
	want := map[string]bool{}
	for _, n := range p.CRDNames {
		want[n] = true
	}
	found := map[string]manifest.Object{}
	for _, o := range objs {
		if manifest.Kind(o) != "CustomResourceDefinition" {
			continue
		}
		name := manifest.Name(o)
		if !want[name] {
			return nil, fmt.Errorf("new CustomResourceDefinition %s: review it and add it to CRDNames of project %s", name, p.Name)
		}
		if _, dup := found[name]; dup {
			return nil, fmt.Errorf("duplicate CustomResourceDefinition %s", name)
		}
		if ns := manifest.Namespace(o); ns != "" {
			return nil, fmt.Errorf("CustomResourceDefinition %s has metadata.namespace %q", name, ns)
		}
		found[name] = o
	}
	if len(p.CRDNames) == 0 {
		return nil, fmt.Errorf("project %s lists no CRDs", p.Name)
	}
	out := make([]manifest.Object, 0, len(p.CRDNames))
	for _, n := range p.CRDNames {
		o, ok := found[n]
		if !ok {
			return nil, fmt.Errorf("CustomResourceDefinition %s not found", n)
		}
		out = append(out, o)
	}
	return out, nil
}

// generateOperator makes a chart for an operator manifest and its custom resource.
func generateOperator(in Input, version string) (map[string][]byte, error) {
	p := in.Project
	objs, err := manifest.Split(in.Operator)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", p.OperatorFile, err)
	}
	if err := checkLayout(p, objs); err != nil {
		return nil, fmt.Errorf("%s %s: upstream layout changed: %w", p.OperatorFile, in.Tag, err)
	}

	var (
		nsLabels []string
		crd      manifest.Object
		rest     []manifest.Object
	)
	for _, o := range objs {
		switch manifest.Kind(o) {
		case "Namespace":
			nsLabels = namespaceLabels(o)
		case "CustomResourceDefinition":
			crd = o
		default:
			rest = append(rest, o)
		}
	}

	images := map[string]bool{}
	for _, o := range rest {
		if err := templateNamespace(p, o); err != nil {
			return nil, err
		}
		if manifest.Kind(o) == "Deployment" {
			if err := templateDeployment(p, in.Tag, o, images); err != nil {
				return nil, fmt.Errorf("Deployment %s: %w", manifest.Name(o), err)
			}
		}
		manifest.SetAnnotation(o, KeepAnnotation, "keep")
	}
	// Fail if the tag or the upstream namespace is still present as a value.
	for _, o := range rest {
		var bad []string
		manifest.WalkStrings(o, manifest.KindName(o), func(path, s string) {
			if strings.Contains(s, in.Tag) {
				bad = append(bad, path+"="+s)
			}
			last := path[strings.LastIndex(path, ".")+1:]
			if s == p.Namespace && strings.Contains(strings.ToLower(last), "namespace") {
				bad = append(bad, path+"="+s)
			}
		})
		if len(bad) > 0 {
			return nil, fmt.Errorf("upstream layout changed: values that the generator did not template: %s", strings.Join(bad, ", "))
		}
	}

	opYAML, err := manifest.Marshal(rest)
	if err != nil {
		return nil, err
	}
	opTpl := toTemplate(p, opYAML)

	crdYAML, err := yaml.Marshal(crd)
	if err != nil {
		return nil, err
	}

	crAPIVersion, crSpec, err := crDefaults(p, in.CR)
	if err != nil {
		return nil, fmt.Errorf("%s %s: %w", p.CRFile, in.Tag, err)
	}
	specYAML, err := yaml.Marshal(crSpec)
	if err != nil {
		return nil, err
	}

	imgList := make([]string, 0, len(images))
	for i := range images {
		imgList = append(imgList, i)
	}
	sort.Strings(imgList)

	data := templateData{
		Project:         p,
		Tag:             in.Tag,
		Version:         version,
		CRAPIVersion:    crAPIVersion,
		CRSpecYAML:      indent(string(specYAML), "    "),
		NamespaceLabels: nsLabels,
		Images:          imgList,
		CRDFile:         "crds/" + p.CRDName + ".yaml",
		FollowImageTag:  p.FollowImageTag && !slices.Contains(upstream.ChartsBeforeFollowImageTag, version),
	}

	header := fmt.Sprintf("# Code generated by chartgen from %s %s %s. DO NOT EDIT.\n", p.Repo, in.Tag, p.OperatorFile)
	files := map[string][]byte{
		data.CRDFile:                             append([]byte(header), crdYAML...),
		"templates/" + p.Name + "-operator.yaml": append([]byte(header), opTpl...),
	}

	if err := renderStatic(files, "operator", data, p.Name); err != nil {
		return nil, err
	}
	return files, nil
}

// renderStatic renders the embedded templates of templates/common and
// templates/<shape> into files. The template delimiters are [[ ]], so that Helm
// expressions pass through. "CHART" in a file name becomes the chart name.
func renderStatic(files map[string][]byte, shape string, data any, chartName string) error {
	for _, dir := range []string{"templates/common", "templates/" + shape} {
		err := fs.WalkDir(staticFS, dir, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return err
			}
			src, err := staticFS.ReadFile(path)
			if err != nil {
				return err
			}
			t, err := template.New(path).Delims("[[", "]]").Funcs(template.FuncMap{"lower": strings.ToLower}).Option("missingkey=error").Parse(string(src))
			if err != nil {
				return fmt.Errorf("parse %s: %w", path, err)
			}
			var buf bytes.Buffer
			if err := t.Execute(&buf, data); err != nil {
				return fmt.Errorf("execute %s: %w", path, err)
			}
			out := strings.TrimPrefix(strings.TrimSuffix(path, ".tmpl"), dir+"/")
			out = strings.ReplaceAll(out, "CHART", chartName)
			files[out] = buf.Bytes()
			return nil
		})
		if err != nil {
			return err
		}
	}
	return nil
}

// checkLayout makes sure that the manifest has the expected kinds and objects.
func checkLayout(p *upstream.Project, objs []manifest.Object) error {
	seen := map[string]bool{}
	count := map[string]int{}
	for _, o := range objs {
		k := manifest.Kind(o)
		if !upstream.AllowedKinds[k] {
			return fmt.Errorf("new kind %s (%s): review it and add it to upstream.AllowedKinds", k, manifest.Name(o))
		}
		kn := manifest.KindName(o)
		if seen[kn] {
			return fmt.Errorf("duplicate object %s", kn)
		}
		seen[kn] = true
		count[k]++
		if ns := manifest.Namespace(o); ns != "" && ns != p.Namespace {
			return fmt.Errorf("%s is in namespace %q, want %q", kn, ns, p.Namespace)
		}
	}
	for _, r := range p.Required {
		if !seen[r] {
			return fmt.Errorf("required object %s not found", r)
		}
	}
	for _, k := range []string{"Namespace", "CustomResourceDefinition", "Deployment"} {
		if count[k] != 1 {
			return fmt.Errorf("found %d objects of kind %s, want exactly 1", count[k], k)
		}
	}
	if !seen["CustomResourceDefinition/"+p.CRDName] {
		return fmt.Errorf("static CRD %s not found", p.CRDName)
	}
	if !seen["Deployment/"+p.DeploymentName] {
		return fmt.Errorf("Deployment %s not found", p.DeploymentName)
	}
	return nil
}

func namespaceLabels(o manifest.Object) []string {
	labels, _ := manifest.Metadata(o)["labels"].(map[string]any)
	var out []string
	for k, v := range labels {
		out = append(out, fmt.Sprintf("%s=%v", k, v))
	}
	sort.Strings(out)
	return out
}

// templateNamespace replaces the upstream namespace in metadata and in binding subjects.
func templateNamespace(p *upstream.Project, o manifest.Object) error {
	md := manifest.Metadata(o)
	if _, ok := md["namespace"]; ok {
		md["namespace"] = phNamespace
	}
	if subjects, ok := o["subjects"].([]any); ok {
		for _, s := range subjects {
			sm, ok := s.(map[string]any)
			if !ok {
				continue
			}
			if ns, ok := sm["namespace"].(string); ok {
				if ns != p.Namespace {
					return fmt.Errorf("%s: subject namespace %q, want %q", manifest.KindName(o), ns, p.Namespace)
				}
				sm["namespace"] = phNamespace
			}
		}
	}
	return nil
}

func templateDeployment(p *upstream.Project, tag string, o manifest.Object, images map[string]bool) error {
	imageRe := regexp.MustCompile(`^` + regexp.QuoteMeta(p.ImageRegistry) + `/([a-z0-9][a-z0-9-]*):` + regexp.QuoteMeta(tag) + `$`)
	spec, _ := o["spec"].(map[string]any)
	tmpl, _ := spec["template"].(map[string]any)
	podSpec, _ := tmpl["spec"].(map[string]any)
	if podSpec == nil {
		return fmt.Errorf("spec.template.spec not found")
	}
	foundEnv := map[string]bool{}
	nContainers := 0
	for _, field := range []string{"initContainers", "containers"} {
		list, _ := podSpec[field].([]any)
		for _, c := range list {
			cm, ok := c.(map[string]any)
			if !ok {
				continue
			}
			nContainers++
			img, _ := cm["image"].(string)
			m := imageRe.FindStringSubmatch(img)
			if m == nil {
				return fmt.Errorf("container image %q does not match %s/<name>:%s", img, p.ImageRegistry, tag)
			}
			images[m[1]] = true
			cm["image"] = fmt.Sprintf(phImage, m[1])
			env, _ := cm["env"].([]any)
			for _, e := range env {
				em, ok := e.(map[string]any)
				if !ok {
					continue
				}
				name, _ := em["name"].(string)
				val, ok := em["value"].(string)
				if !ok {
					continue
				}
				switch {
				case val == tag:
					em["value"] = phVersion
					foundEnv[name] = true
				case imageRe.MatchString(val):
					n := imageRe.FindStringSubmatch(val)[1]
					images[n] = true
					em["value"] = fmt.Sprintf(phImage, n)
					foundEnv[name] = true
				}
			}
		}
	}
	if nContainers == 0 {
		return fmt.Errorf("no containers found")
	}
	for _, e := range append(append([]string{}, p.VersionEnv...), p.ImageEnv...) {
		if !foundEnv[e] {
			return fmt.Errorf("env var %s with the upstream version or image not found", e)
		}
	}
	return nil
}

var braces = regexp.MustCompile(`\{\{|\}\}`)

// escapeBraces makes literal "{{" and "}}" safe in a Helm template.
func escapeBraces(s string) string {
	return braces.ReplaceAllStringFunc(s, func(m string) string {
		return `{{ "` + m + `" }}`
	})
}

// toTemplate escapes literal braces and turns placeholders into template expressions.
func toTemplate(p *upstream.Project, b []byte) []byte {
	s := escapeBraces(string(b))
	s = strings.ReplaceAll(s, phNamespace, `{{ .Release.Namespace }}`)
	s = strings.ReplaceAll(s, phVersion, `{{ .Values.image.tag | quote }}`)
	s = phImageRe.ReplaceAllString(s, `{{ include "`+p.Name+`.image" (list . "$1") | quote }}`)
	return []byte(s)
}

// crDefaults reads the upstream CR file and returns its apiVersion and the default spec:
// the upstream spec without empty fields, plus uninstallStrategy.
func crDefaults(p *upstream.Project, data []byte) (string, map[string]any, error) {
	objs, err := manifest.Split(data)
	if err != nil {
		return "", nil, err
	}
	if len(objs) != 1 {
		return "", nil, fmt.Errorf("found %d objects, want 1", len(objs))
	}
	cr := objs[0]
	if manifest.Kind(cr) != p.CRKind || manifest.Name(cr) != p.CRName {
		return "", nil, fmt.Errorf("found %s, want %s/%s", manifest.KindName(cr), p.CRKind, p.CRName)
	}
	for k := range manifest.Metadata(cr) {
		if k != "name" && k != "namespace" {
			return "", nil, fmt.Errorf("unexpected metadata.%s", k)
		}
	}
	for k := range cr {
		if k != "apiVersion" && k != "kind" && k != "metadata" && k != "spec" {
			return "", nil, fmt.Errorf("unexpected top-level field %s", k)
		}
	}
	spec, _ := cr["spec"].(map[string]any)
	if spec == nil {
		spec = map[string]any{}
	}
	spec = manifest.PruneEmpty(spec).(map[string]any)
	if _, ok := spec["uninstallStrategy"]; !ok {
		spec["uninstallStrategy"] = "BlockUninstallIfWorkloadsExist"
	}
	return manifest.APIVersion(cr), spec, nil
}

// ExpectedCR returns the custom resource that the chart must render with default values.
func ExpectedCR(p *upstream.Project, data []byte, namespace string) (manifest.Object, error) {
	apiVersion, spec, err := crDefaults(p, data)
	if err != nil {
		return nil, err
	}
	md := map[string]any{"name": p.CRName}
	if p.CRNamespaced {
		md["namespace"] = namespace
	}
	return manifest.Object{"apiVersion": apiVersion, "kind": p.CRKind, "metadata": md, "spec": spec}, nil
}

func indent(s, prefix string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = prefix + l
		}
	}
	return strings.Join(lines, "\n")
}
